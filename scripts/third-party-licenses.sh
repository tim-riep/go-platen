#!/bin/sh
# Regenerates THIRD_PARTY_LICENSES from the dependencies compiled into the
# platen binary. Requires go-licenses v2:
#   go install github.com/google/go-licenses/v2@latest
set -eu
cd "$(dirname "$0")/.."
export GOOS=linux GOARCH=amd64
{
	cat <<'HEADER'
platen includes third-party software. This file lists every Go module that
is compiled into the platen binary, with its license, its copyright notice
and the location of its source code. It is generated by
scripts/third-party-licenses.sh; do not edit by hand.

Modules licensed under the Mozilla Public License 2.0 are used unmodified.
Their source code is available at the location given for each module.
HEADER
	cat scripts/third_party_extra.txt
	# The ignored modules are added from third_party/manual below.
	go-licenses report ./... \
		--template scripts/third_party_licenses.tpl \
		--ignore github.com/tim-riep/go-platen \
		--ignore github.com/jackpal/go-nat-pmp \
		--ignore github.com/jmespath/go-jmespath 2>/dev/null
	for meta in $(find third_party/manual -name METADATA | sort); do
		dir=$(dirname "$meta")
		module=$(sed -n 's/^module=//p' "$meta")
		version=$(sed -n 's/^version=//p' "$meta")
		license=$(sed -n 's/^license=//p' "$meta")
		source=$(sed -n 's/^source=//p' "$meta")
		printf '\n================================================================================\n'
		printf '%s %s\nLicense: %s (reviewed manually, see third_party/manual)\nSource: %s (version %s)\n' \
			"$module" "$version" "$license" "$source" "$version"
		printf -- '--------------------------------------------------------------------------------\n'
		cat "$dir/LICENSE"
		printf '\n'
	done
} > THIRD_PARTY_LICENSES
